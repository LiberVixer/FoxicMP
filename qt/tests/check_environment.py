#!/usr/bin/env python3
"""Fail early with an actionable message when the Qt test corpus is missing."""
from __future__ import annotations

import argparse
import os
import shutil
import subprocess
import sys
from pathlib import Path


def require_command(name: str, failures: list[str]) -> None:
    if shutil.which(name) is None:
        failures.append(f"required command is missing: {name}")


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--media", type=Path, required=True,
                        help="directory generated by generate_media.py")
    parser.add_argument("--devices", type=Path,
                        help="directory generated by generate_dvd.py")
    parser.add_argument("--display", action="store_true",
                        help="also require an X11 or Wayland display")
    parser.add_argument("--audio", action="store_true",
                        help="also require pactl and a configured PulseAudio server")
    args = parser.parse_args()
    failures: list[str] = []
    for command in ("ffmpeg", "ffprobe"):
        require_command(command, failures)

    expected = ("Русский H264.mp4", "HEVC.mov", "VP9.webm", "AV1.mkv",
                "MPEG4.avi", "chapters.mkv", "subtitle.srt")
    if not args.media.is_dir():
        failures.append(f"media corpus directory does not exist: {args.media}")
    else:
        for name in expected:
            if not (args.media / name).is_file():
                failures.append(f"media fixture is missing: {args.media / name}")

    if args.devices is not None:
        for command in ("dvdauthor", "genisoimage"):
            require_command(command, failures)
        for name in ("DVD", "test-dvd.iso"):
            path = args.devices / name
            if not path.exists():
                failures.append(f"DVD fixture is missing: {path}")

    if args.display and not (os.environ.get("DISPLAY") or
                              os.environ.get("WAYLAND_DISPLAY")):
        failures.append("no DISPLAY or WAYLAND_DISPLAY is set")
    if args.audio:
        require_command("pactl", failures)
        if shutil.which("pactl"):
            try:
                probe = subprocess.run(["pactl", "info"],
                                       capture_output=True, timeout=5)
                if probe.returncode:
                    failures.append("PulseAudio-compatible server is unavailable")
            except (OSError, subprocess.TimeoutExpired):
                failures.append("PulseAudio-compatible server did not respond")

    if failures:
        print("FoxicMP Qt test environment is incomplete:", file=sys.stderr)
        for failure in failures:
            print(f"  - {failure}", file=sys.stderr)
        print("See the Verify section in qt/README.md for dependencies, "
              "fixture generation and the isolated test runner.",
              file=sys.stderr)
        return 2
    print("FoxicMP Qt test environment: ready")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
